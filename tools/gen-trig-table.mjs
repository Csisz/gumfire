// Generates packages/sim/src/core/trigTables.ts.
// Run once with `pnpm gen:trig`; the output is committed so the simulation never
// calls floating-point trigonometry at runtime (see ADR-002).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ANGLE_STEPS = 4096; // full circle
const ONE = 65536; // Q16 fixed point
const ATAN_STEPS = 1024; // ratio resolution for one octant

const sin = [];
for (let i = 0; i < ANGLE_STEPS; i++) {
  sin.push(Math.round(Math.sin((i / ANGLE_STEPS) * 2 * Math.PI) * ONE));
}

// atan(i / ATAN_STEPS) expressed in angle units, for i = 0..ATAN_STEPS (0..45 degrees)
const atan = [];
for (let i = 0; i <= ATAN_STEPS; i++) {
  atan.push(Math.round((Math.atan(i / ATAN_STEPS) / (2 * Math.PI)) * ANGLE_STEPS));
}

const chunk = (arr) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16) lines.push('  ' + arr.slice(i, i + 16).join(', ') + ',');
  return lines.join('\n');
};

const out = `// AUTO-GENERATED by tools/gen-trig-table.mjs — do not edit by hand.
// sin table: ${ANGLE_STEPS} entries, Q16 (65536 = 1.0). atan table: ${ATAN_STEPS + 1} entries in angle units.

export const SIN_TABLE: Int32Array = Int32Array.from([
${chunk(sin)}
]);

export const ATAN_TABLE: Int16Array = Int16Array.from([
${chunk(atan)}
]);
`;

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'packages', 'sim', 'src', 'core', 'trigTables.ts');
writeFileSync(target, out);
console.log(`wrote ${target}`);
